// ひな型の後ろに付ける口調の指示。文字数・改行ルールは守り、6段階の流れは目安として自然に入れる
function toneSection(tone) {
  return `## 口調パターン（${tone.id}. ${tone.name}）
ペルソナ: ${tone.persona}
トーン: ${tone.tone}

【口調指定】
${tone.instruction}

【文脈構成（目安）】
${tone.context.map((c, i) => `${i + 1}. ${c}`).join('\n')}

【口調パターンとひな型の優先順位】
- 文字数（本文の合計は160文字以上200文字以内。160文字より短くしない）と改行ルール（1文目の後だけ改行し、2文目以降は1つの段落）は必ず守る
- 文脈構成の6段階はなるべく目安にして、自然な日本語でつなげる。そのため、ひな型の「構成ルール」の4文の型や文の数に厳密に合わせなくてよい（1文目が悩みを特定するフックであることは守る）
- 語尾と語り口は【口調指定】に合わせる。3パターン（A/B/C）の切り口、伸びる確率の採点、トーン指示（絵文字・具体的な数字など）、出力形式はひな型どおり
`;
}

